# Initialize Ralph structure in workspace
# Usage: workspace_init_ralph <vm_name>
workspace_init_ralph() {
    local vm_name="$1"

    if [[ -z "$vm_name" ]]; then
        log_error "VM name required"
        return 1
    fi

    _check_vm_running "$vm_name" || return 1

    local vm_ip ssh_key_path workspace_name workspace_path
    vm_ip=$(_get_vm_ip "$vm_name")
    ssh_key_path=$(_get_vm_ssh_key "$vm_name")
    workspace_name=$(registry_get "$vm_name" ".workspace" 2>/dev/null)

    if [[ -z "$workspace_name" || "$workspace_name" == "null" ]]; then
        workspace_name="$vm_name"
    fi

    workspace_path="${WORKSPACE_BASE}"

    log_info "Initializing Ralph in workspace '$workspace_name'..."

    # Check if Ralph configuration exists
    if ! _ssh_cmd "$vm_name" "test -d '$workspace_path/.ralph'"; then
        log_error "Ralph configuration not found in $workspace_path/.ralph"
        log_info "Initialize workspace first with: foundry workspace init $vm_name <config.json>"
        return 1
    fi

    # Ensure logs directory exists
    _ssh_cmd "$vm_name" "mkdir -p '${workspace_path}/logs'"

    # Check if Ralph is installed
    if _ssh_cmd "$vm_name" "command -v ralph >/dev/null 2>&1"; then
        log_info "Ralph is installed and ready"
    else
        log_warn "Ralph binary not found in VM PATH."
        log_warn "Ensure the VM image has Ralph installed."
    fi

    log_info "Ralph initialization verified"
    return 0
}

