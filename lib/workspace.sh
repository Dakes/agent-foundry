# Edit a workspace file via SSH
# Usage: workspace_edit <vm_name> <file>
workspace_edit() {
    local vm_name="$1"
    local file="$2"

    if [[ -z "$vm_name" ]]; then
        log_error "VM name required"
        return 1
    fi

    if [[ -z "$file" ]]; then
        log_error "File path required"
        return 1
    fi

    _check_vm_running "$vm_name" || return 1

    local vm_ip ssh_key_path workspace_name workspace_path
    vm_ip=$(_get_vm_ip "$vm_name")
    ssh_key_path=$(_get_vm_ssh_key "$vm_name")
    workspace_name=$(registry_get "$vm_name" ".workspace" 2>/dev/null)

    if [[ -z "$workspace_name" || "$workspace_name" == "null" ]]; then
        workspace_name="$vm_name"
    fi

    workspace_path="${WORKSPACE_BASE}"

    # Determine full path
    local full_path
    if [[ "$file" == /* ]]; then
        full_path="$file"
    else
        full_path="${workspace_path}/${file}"
    fi

    # Check if file exists
    if ! _ssh_cmd "$vm_name" "test -f '$full_path'"; then
        log_warn "File does not exist: $full_path"
        if confirm "Create new file?"; then
            _ssh_cmd "$vm_name" "touch '$full_path'"
        else
            return 1
        fi
    fi

    log_info "Opening $full_path in editor..."

    # Determine editor
    local editor="${EDITOR:-vim}"

    # Open SSH connection with editor
    exec ssh -t ${ssh_key_path:+-i "$ssh_key_path"} $FOUNDRY_SSH_OPTS "${FOUNDRY_SSH_USER}@${vm_ip}" "$editor '$full_path'"
}

